function centavos(reais: number): number {
  return Math.round(reais * 100);
}

async function main() {
  for (const contrato of CONTRATOS) {
    if (contrato.linhas.length !== 72) {
      throw new Error(`Contrato ${contrato.numero}: esperava 72 linhas, tem ${contrato.linhas.length}`);
    }
    const passivo = await prisma.passivo.findUniqueOrThrow({ where: { id: contrato.passivoId } });
    console.log(`\nContrato ${contrato.numero} (${passivo.nome})`);

    // Conferência antes de gravar: soma dos Principais deve bater com o
    // Valor financiado documentado (Principal + Juros = Valor parcela em
    // toda linha, e a soma de Principal ao longo de 72 parcelas amortiza
    // o valor financiado inteiro).
    const somaPrincipal = contrato.linhas.reduce((s, [, , principal]) => s + principal, 0);
    const diff = Math.abs(somaPrincipal - contrato.valorFinanciado);
    console.log(`  Soma Principal: R$${somaPrincipal.toFixed(2)} | Valor financiado: R$${contrato.valorFinanciado.toFixed(2)} | diff: R$${diff.toFixed(2)}`);
    if (diff > 1) throw new Error(`Contrato ${contrato.numero}: soma de Principal não bate com valor financiado (diff R$${diff.toFixed(2)})`);

    // Confere Principal+Juros=ValorParcela em cada linha.
    for (const [numero, , principal] of contrato.linhas) {
      const juros = contrato.valorParcela - principal;
      if (juros < -0.01) throw new Error(`Contrato ${contrato.numero} parcela ${numero}: juros negativo (${juros})`);
    }

    await prisma.passivoParcelaCronograma.createMany({
      data: contrato.linhas.map(([numero, vencimento, principal, saldoDevedor]) => ({
        passivoId: contrato.passivoId,
        numeroParcela: numero,
        vencimento: dataBR(vencimento),
        principalCentavos: centavos(principal),
        jurosCentavos: centavos(contrato.valorParcela - principal),
        valorParcelaCentavos: centavos(contrato.valorParcela),
        saldoDevedorCentavos: centavos(saldoDevedor),
        documentoId: contrato.documentoId,
      })),
    });
    console.log(`  72 parcelas gravadas.`);
  }

  const total = await prisma.passivoParcelaCronograma.count();
  console.log(`\nTotal de linhas no banco: ${total}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
